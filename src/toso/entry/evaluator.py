"""TOSO Entry and Invalidation Evaluator.

Provides deterministic functions for:
- Calculating deterministic invalidation levels from strategy rules (INV-006).
- Creating CoreEntryOrder from approved TradeSignal and independent verification.
- Ratcheting invalidations in a tighten-only direction (INV-005).
- Strictly rejecting external/agent override attempts (AC-003).
"""

import math
import uuid
from datetime import datetime

from toso.config.models import RiskConfig, StrategyConfig
from toso.entry.errors import (
    AgentOverrideRejectedError,
    InvalidationLooseningError,
    InvalidEntryOrderError,
    InvalidInvalidationError,
    MissingInvalidationError,
)
from toso.entry.models import (
    CoreEntryOrder,
    GapSlippageRiskModel,
    InvalidationDefinition,
)
from toso.signals.models import SignalType, TradeSignal


def calculate_deterministic_invalidation(
    entry_price: float, atr: float, config: StrategyConfig, timestamp: datetime
) -> InvalidationDefinition:
    """Calculate deterministic stop invalidation price from strategy config and ATR.

    Formula: entry_price - (invalidation_atr_multiple * atr)

    Args:
        entry_price: The trade entry reference price.
        atr: The calculated Average True Range value.
        config: Approved StrategyConfig parameters.
        timestamp: Time of invalidation establishment.

    Returns:
        Immutable InvalidationDefinition.

    Raises:
        InvalidInvalidationError: If calculated invalidation is non-positive or >= entry_price.
    """
    if entry_price <= 0:
        raise InvalidEntryOrderError(f"Entry price must be positive, got {entry_price}.")
    if atr <= 0:
        raise InvalidInvalidationError(f"Reference ATR must be positive, got {atr}.")

    stop_distance = round(config.invalidation_atr_multiple * atr, 4)
    invalidation_price = round(entry_price - stop_distance, 4)

    if invalidation_price <= 0:
        raise InvalidInvalidationError(
            f"Calculated invalidation price ({invalidation_price:.4f}) is non-positive. "
            f"Entry {entry_price:.2f} with {config.invalidation_atr_multiple}x ATR {atr:.2f} "
            "exceeds asset value."
        )

    if invalidation_price >= entry_price:
        raise InvalidInvalidationError(
            f"Calculated invalidation price ({invalidation_price:.4f}) cannot be greater than "
            f"or equal to entry price ({entry_price:.4f})."
        )

    return InvalidationDefinition(
        price=invalidation_price,
        invalidation_type="ATR_STOP",
        atr_multiple=config.invalidation_atr_multiple,
        reference_atr=atr,
        established_at=timestamp,
        is_ratcheted=False,
        reason=(
            f"Deterministic {config.invalidation_atr_multiple}x ATR stop "
            f"({entry_price:.2f} - {stop_distance:.2f} = {invalidation_price:.2f})."
        ),
    )


def create_entry_from_signal(
    signal: TradeSignal,
    strategy_config: StrategyConfig,
    risk_config: RiskConfig,
    order_id: str | None = None,
) -> CoreEntryOrder:
    """Construct an authoritative CoreEntryOrder from an approved TradeSignal.

    Independently verifies and cross-checks the signal's invalidation price against
    the deterministic strategy rules to guarantee mathematical determinism (INV-006).

    Args:
        signal: TradeSignal generated by Core Strategy.
        strategy_config: Approved StrategyConfig.
        risk_config: Approved RiskConfig.
        order_id: Optional explicit order identifier.

    Returns:
        Frozen, immutable CoreEntryOrder.

    Raises:
        InvalidEntryOrderError: If signal is not BULLISH_ENTRY.
        MissingInvalidationError: If signal lacks invalidation_price.
        InvalidInvalidationError: If signal invalidation does not match deterministic calculation.
    """
    if signal.signal_type != SignalType.BULLISH_ENTRY:
        raise InvalidEntryOrderError(
            f"Cannot create CoreEntryOrder from signal type '{signal.signal_type}'. "
            "Only BULLISH_ENTRY signals are eligible for Core entry orders."
        )

    if signal.invalidation_price is None:
        raise MissingInvalidationError(
            f"TradeSignal for {signal.symbol} lacks required invalidation_price."
        )

    # Independently recalculate expected invalidation to prevent reliance
    # on untrusted or manipulated input
    expected_invalidation = calculate_deterministic_invalidation(
        entry_price=signal.price,
        atr=signal.indicators.atr,
        config=strategy_config,
        timestamp=signal.timestamp,
    )

    if not math.isclose(signal.invalidation_price, expected_invalidation.price, abs_tol=1e-4):
        raise InvalidInvalidationError(
            f"Signal invalidation price ({signal.invalidation_price}) does not match "
            f"deterministic calculation ({expected_invalidation.price}) "
            f"for strategy {strategy_config.strategy_id}."
        )

    risk_accounting = GapSlippageRiskModel.compute(
        entry_price=signal.price,
        invalidation_price=expected_invalidation.price,
        slippage_buffer_pct=risk_config.slippage_buffer_pct,
    )

    assigned_id = order_id or f"ENTRY-{signal.symbol}-{uuid.uuid4().hex[:8].upper()}"

    return CoreEntryOrder(
        order_id=assigned_id,
        symbol=signal.symbol,
        timestamp=signal.timestamp,
        side="BUY",
        entry_price=signal.price,
        invalidation=expected_invalidation,
        risk_accounting=risk_accounting,
        signal_id=f"{signal.symbol}-{int(signal.timestamp.timestamp())}",
        reason=signal.reason,
    )


def ratchet_invalidation(
    current_order: CoreEntryOrder,
    new_stop_price: float,
    timestamp: datetime,
    reason: str,
    risk_config: RiskConfig,
) -> CoreEntryOrder:
    """Ratchet an established invalidation tighter to reduce risk or lock profit (INV-005).

    Enforces the anti-loosening invariant: the stop price can only increase for long positions.
    Any attempt to lower the invalidation fails closed with InvalidationLooseningError.

    Args:
        current_order: The active CoreEntryOrder.
        new_stop_price: Proposed new invalidation price.
        timestamp: Time of the ratchet event.
        reason: Deterministic rationale for tightening.
        risk_config: Approved RiskConfig.

    Returns:
        New immutable CoreEntryOrder reflecting the ratcheted invalidation and updated risk.

    Raises:
        InvalidationLooseningError: If new_stop_price < current_order.invalidation.price.
        InvalidInvalidationError: If new_stop_price <= 0.
    """
    if new_stop_price <= 0:
        raise InvalidInvalidationError(
            f"Ratcheted invalidation price must be positive, got {new_stop_price}."
        )

    current_stop = current_order.invalidation.price
    if new_stop_price < current_stop:
        raise InvalidationLooseningError(
            f"Cannot loosen invalidation for {current_order.symbol} from {current_stop:.2f} "
            f"down to {new_stop_price:.2f}. Anti-loosening rule (INV-005) strictly prohibits "
            "widening risk or averaging down."
        )

    if math.isclose(new_stop_price, current_stop, abs_tol=1e-4):
        return current_order

    new_invalidation = InvalidationDefinition(
        price=round(new_stop_price, 4),
        invalidation_type=current_order.invalidation.invalidation_type,
        atr_multiple=current_order.invalidation.atr_multiple,
        reference_atr=current_order.invalidation.reference_atr,
        established_at=timestamp,
        is_ratcheted=True,
        reason=reason,
    )

    new_risk_accounting = GapSlippageRiskModel.compute(
        entry_price=current_order.entry_price,
        invalidation_price=new_invalidation.price,
        slippage_buffer_pct=risk_config.slippage_buffer_pct,
    )

    return CoreEntryOrder(
        order_id=current_order.order_id,
        symbol=current_order.symbol,
        timestamp=current_order.timestamp,
        side=current_order.side,
        entry_price=current_order.entry_price,
        invalidation=new_invalidation,
        risk_accounting=new_risk_accounting,
        signal_id=current_order.signal_id,
        reason=f"{current_order.reason} | Ratcheted: {reason}",
    )


def reject_agent_invalidation_override(
    current_order: CoreEntryOrder,
    proposed_price: float,
    agent_id: str = "ScientistAgent",
) -> None:
    """Strictly reject discretionary or agent-originated modifications to invalidation (AC-003).

    TOSO rules state that invalidations are governed strictly by deterministic strategy rules.
    Agent proposals to adjust or delay invalidations are rejected fail-closed.

    Args:
        current_order: The active CoreEntryOrder.
        proposed_price: Price proposed by external agent.
        agent_id: Identifier of the proposing entity.

    Raises:
        AgentOverrideRejectedError: Always raised to enforce safety boundary.
    """
    raise AgentOverrideRejectedError(
        f"Agent '{agent_id}' attempted to override invalidation from "
        f"{current_order.invalidation.price:.2f} to {proposed_price:.2f}. "
        "Discretionary and LLM agent overrides of deterministic invalidations "
        "are strictly prohibited."
    )
